import { describe, expect, it } from "vitest";
import { buildPublicInspectionUrl, isPublicInspectionToken } from "../lib/public-link";

describe("public inspection links", () => {
  it("builds a shareable URL without duplicating the slash", () => {
    expect(buildPublicInspectionUrl("https://example.com/", "a".repeat(64))).toBe(`https://example.com/inspection/public?token=${"a".repeat(64)}`);
  });

  it("accepts only the hexadecimal token shape generated by the server", () => {
    expect(isPublicInspectionToken("a".repeat(64))).toBe(true);
    expect(isPublicInspectionToken("a".repeat(63))).toBe(false);
    expect(isPublicInspectionToken("z".repeat(64))).toBe(false);
  });
});
